"""Generate hac_statsmodels_fixture.hpp — the W0-E0a statsmodels reference for eval/hac.hpp.

Run (no network, statsmodels + numpy already installed for this interpreter):

    py -3.12 atx-engine/tests/eval/fixtures/gen_hac_statsmodels_fixture.py

It writes `hac_statsmodels_fixture.hpp` beside this script. For three deterministic series
it records, per (kernel, lag, use_correction) case, the HAC t-statistic and standard error of
the mean from

    sm.OLS(y, np.ones(n)).fit(cov_type="HAC",
                              cov_kwds={"maxlags": L, "kernel": k, "use_correction": c})

plus statsmodels' own default lag floor(4 (n/100)^(2/9)) (`S_hac_simple(nlags=None)`), the
Newey-West (1994) automatic Bartlett lag and the Politis-White (2004) automatic block length
from an independent numpy transcription of the published formulas (statsmodels ships
neither). Series values are printed with repr(), so the C++ test reads the identical doubles.
"""

from __future__ import annotations

import math
import pathlib
import sys

import numpy as np
import statsmodels
import statsmodels.api as sm
from statsmodels.stats import sandwich_covariance as sw


def make_series() -> dict[str, np.ndarray]:
    rng = np.random.RandomState(20260924)
    # AR(1), phi = 0.6, n = 300, non-zero mean.
    ar = np.empty(300)
    prev = 0.0
    for i in range(300):
        prev = 0.6 * prev + rng.standard_normal()
        ar[i] = 0.05 + 0.1 * prev
    # Equal-weight MA(20) (the overlap of a 21-day forward return), n = 500.
    eps = rng.standard_normal(520)
    ma = np.array([0.02 + 0.01 * eps[i : i + 21].sum() for i in range(500)])
    # Short white noise, n = 25.
    wn = 0.1 + rng.standard_normal(25)
    return {"ar1": ar, "ma20": ma, "wn25": wn}


CASES = [
    ("bartlett", 0, False),
    ("bartlett", 0, True),
    ("bartlett", 5, False),
    ("bartlett", 5, True),
    ("bartlett", 20, False),
    ("bartlett", 20, True),
    ("uniform", 5, False),
    ("uniform", 20, False),
    ("uniform", 20, True),
]


def hac_fit(y: np.ndarray, kernel: str, lag: int, corr: bool) -> tuple[float, float]:
    res = sm.OLS(y, np.ones(len(y))).fit(
        cov_type="HAC", cov_kwds={"maxlags": lag, "kernel": kernel, "use_correction": corr}
    )
    return float(res.tvalues[0]), float(res.bse[0])


def rule_of_thumb(n: int) -> int:
    return int(np.floor(4 * (n / 100.0) ** (2.0 / 9.0)))


def nw94_lag(y: np.ndarray) -> int:
    """Newey-West (1994) automatic bandwidth, Bartlett kernel, no pre-whitening."""
    n = len(y)
    q = rule_of_thumb(n)
    e = y - y.mean()
    g = [float(e[j:] @ e[: n - j]) / n for j in range(q + 1)]
    s0 = g[0] + 2.0 * sum(g[1:])
    s1 = 2.0 * sum(j * g[j] for j in range(1, q + 1))
    if s0 <= 0.0:
        return q
    gamma = 1.1447 * ((s1 / s0) ** 2) ** (1.0 / 3.0)
    lag = math.floor(gamma * n ** (1.0 / 3.0))
    return int(min(max(lag, 0), n - 1))


def politis_white(y: np.ndarray) -> tuple[float, float]:
    """Politis & White (2004) with Patton-Politis-White (2009) correction (b_CB, b_SB)."""
    n = len(y)
    e = y - y.mean()
    acov = lambda k: float(e[k:] @ e[: n - k]) / n  # noqa: E731
    r0 = acov(0)
    kn = max(5, int(math.floor(math.log10(n))))
    m_max = min(int(math.ceil(math.sqrt(n))) + kn, n - 1)
    crit = 2.0 * math.sqrt(math.log10(n) / n)
    m_hat = m_max
    for cand in range(0, m_max - kn + 1):
        if all(abs(acov(cand + k) / r0) < crit for k in range(1, kn + 1)):
            m_hat = cand
            break
    big_m = min(2 * max(m_hat, 1), m_max)
    g = 0.0
    g0 = r0
    for k in range(1, big_m + 1):
        ratio = k / big_m
        lam = 1.0 if ratio <= 0.5 else 2.0 * (1.0 - ratio)
        rk = acov(k)
        g += 2.0 * lam * k * rk
        g0 += 2.0 * lam * rk
    b_max = math.ceil(min(3.0 * math.sqrt(n), n / 3.0))
    b_cb = ((2.0 * g * g) / ((4.0 / 3.0) * g0 * g0)) ** (1.0 / 3.0) * n ** (1.0 / 3.0)
    b_sb = ((2.0 * g * g) / (2.0 * g0 * g0)) ** (1.0 / 3.0) * n ** (1.0 / 3.0)
    return min(b_cb, b_max), min(b_sb, b_max)


def main() -> int:
    series = make_series()
    out = []
    out.append("#pragma once")
    out.append("")
    out.append("// GENERATED by gen_hac_statsmodels_fixture.py — do not edit by hand.")
    out.append(f"// statsmodels {statsmodels.__version__}, numpy {np.__version__}.")
    out.append("")
    out.append("#include <array>")
    out.append("")
    out.append("namespace atx_test_w0_e0a_hac_fixture {")
    out.append("")
    out.append("struct HacCase {")
    out.append("  const char *series;")
    out.append("  bool uniform;")
    out.append("  unsigned lag;")
    out.append("  bool correction;")
    out.append("  double t;")
    out.append("  double se;")
    out.append("};")
    out.append("")
    out.append("struct SeriesMeta {")
    out.append("  const char *series;")
    out.append("  unsigned rule_of_thumb_lag;")
    out.append("  unsigned nw94_lag;")
    out.append("  double pw_circular;")
    out.append("  double pw_stationary;")
    out.append("};")
    out.append("")
    for name, y in series.items():
        out.append(f"inline constexpr std::array<double, {len(y)}> k_{name}{{")
        vals = [repr(float(v)) for v in y]
        for i in range(0, len(vals), 4):
            out.append("    " + ", ".join(vals[i : i + 4]) + ",")
        out.append("};")
        out.append("")
    cases = []
    for name, y in series.items():
        for kernel, lag, corr in CASES:
            if lag >= len(y):
                continue
            t, se = hac_fit(y, kernel, lag, corr)
            cases.append(
                f'    HacCase{{"{name}", {str(kernel == "uniform").lower()}, {lag}U, '
                f"{str(corr).lower()}, {t!r}, {se!r}}},"
            )
    out.append(f"inline constexpr std::array<HacCase, {len(cases)}> kHacCases{{{{")
    out.extend(cases)
    out.append("}};")
    out.append("")
    metas = []
    for name, y in series.items():
        # statsmodels' own default-lag path, cross-checked against the formula.
        s_default = sw.S_hac_simple(y - y.mean(), nlags=None)
        s_formula = sw.S_hac_simple(y - y.mean(), nlags=rule_of_thumb(len(y)))
        assert np.allclose(s_default, s_formula, rtol=0, atol=0)
        cb, sb = politis_white(y)
        metas.append(
            f'    SeriesMeta{{"{name}", {rule_of_thumb(len(y))}U, {nw94_lag(y)}U, {cb!r}, {sb!r}}},'
        )
    out.append(f"inline constexpr std::array<SeriesMeta, {len(metas)}> kSeriesMeta{{{{")
    out.extend(metas)
    out.append("}};")
    out.append("")
    out.append("} // namespace atx_test_w0_e0a_hac_fixture")
    out.append("")
    target = pathlib.Path(__file__).with_name("hac_statsmodels_fixture.hpp")
    target.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {target} ({len(cases)} HAC cases)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
