#include "governance_store.hpp"
#include "store_sql.hpp"

namespace atx::server::governance_detail {
void migrate(sqlite3* db) {
    store_detail::Transaction transaction(db);
    store_detail::execute(db,
        "ALTER TABLE jobs ADD COLUMN actor_id TEXT NOT NULL DEFAULT 'migration_unknown';"
        "ALTER TABLE workspaces ADD COLUMN actor_id TEXT NOT NULL DEFAULT 'migration_unknown';"
        "ALTER TABLE alpha_revisions ADD COLUMN actor_id TEXT NOT NULL "
        "DEFAULT 'migration_unknown';"
        "ALTER TABLE experiments ADD COLUMN actor_id TEXT NOT NULL DEFAULT 'migration_unknown';"
        "CREATE TRIGGER job_actor_immutable BEFORE UPDATE OF actor_id ON jobs "
        "BEGIN SELECT RAISE(ABORT,'job actor is immutable'); END;"
        "CREATE TABLE audit_records(sequence INTEGER PRIMARY KEY AUTOINCREMENT,"
        "entity_type TEXT NOT NULL,entity_id TEXT NOT NULL,action TEXT NOT NULL,"
        "actor_id TEXT NOT NULL CHECK(length(actor_id) BETWEEN 1 AND 64),"
        "revision INTEGER NOT NULL CHECK(revision>=0),metadata_json TEXT NOT NULL "
        "CHECK(length(CAST(metadata_json AS BLOB))<=4096),created_at_ms INTEGER NOT NULL);"
        "CREATE INDEX audit_entity ON audit_records(entity_type,entity_id,sequence DESC);"
        "CREATE INDEX audit_id ON audit_records(entity_id,sequence DESC);"
        "CREATE INDEX audit_actor ON audit_records(actor_id,sequence DESC);"
        "CREATE TRIGGER audit_no_update BEFORE UPDATE ON audit_records "
        "BEGIN SELECT RAISE(ABORT,'audit history is immutable'); END;"
        "CREATE TRIGGER audit_no_delete BEFORE DELETE ON audit_records "
        "BEGIN SELECT RAISE(ABORT,'audit history is immutable'); END;"
        "CREATE TABLE review_submissions(id TEXT PRIMARY KEY,alpha_id TEXT NOT NULL,"
        "alpha_revision INTEGER NOT NULL CHECK(alpha_revision>=1),request_sha256 TEXT NOT NULL,"
        "requester_actor_id TEXT NOT NULL,author_actor_id TEXT NOT NULL,note TEXT NOT NULL "
        "CHECK(length(CAST(note AS BLOB))<=4096),evidence_json TEXT NOT NULL "
        "CHECK(length(CAST(evidence_json AS BLOB))<=98304),created_at_ms INTEGER NOT NULL,"
        "idempotency_key TEXT UNIQUE,semantic_json TEXT NOT NULL "
        "CHECK(length(CAST(semantic_json AS BLOB))<=8192),"
        "FOREIGN KEY(alpha_id,alpha_revision) REFERENCES alpha_revisions(alpha_id,revision));"
        "CREATE INDEX review_alpha ON review_submissions(alpha_id,created_at_ms DESC,id DESC);"
        "CREATE TABLE review_heads(id TEXT PRIMARY KEY REFERENCES review_submissions(id),"
        "state TEXT NOT NULL CHECK(state IN ('submitted','approved','rejected','withdrawn')),"
        "revision INTEGER NOT NULL CHECK(revision>=1),updated_at_ms INTEGER NOT NULL);"
        "CREATE INDEX review_updated ON review_heads(updated_at_ms DESC,id DESC);"
        "CREATE TABLE review_decisions(id TEXT PRIMARY KEY,review_id TEXT NOT NULL "
        "REFERENCES review_submissions(id),revision INTEGER NOT NULL CHECK(revision>=2),"
        "state TEXT NOT NULL CHECK(state IN ('approved','rejected','withdrawn')),"
        "actor_id TEXT NOT NULL,rationale TEXT NOT NULL "
        "CHECK(length(CAST(rationale AS BLOB))<=4096),created_at_ms INTEGER NOT NULL,"
        "UNIQUE(review_id,revision));"
        "CREATE TRIGGER review_submission_no_update BEFORE UPDATE ON review_submissions "
        "BEGIN SELECT RAISE(ABORT,'submitted review evidence is immutable'); END;"
        "CREATE TRIGGER review_submission_no_delete BEFORE DELETE ON review_submissions "
        "BEGIN SELECT RAISE(ABORT,'submitted review evidence is immutable'); END;"
        "CREATE TRIGGER review_decision_no_update BEFORE UPDATE ON review_decisions "
        "BEGIN SELECT RAISE(ABORT,'review decisions are immutable'); END;"
        "CREATE TRIGGER review_decision_no_delete BEFORE DELETE ON review_decisions "
        "BEGIN SELECT RAISE(ABORT,'review decisions are immutable'); END;"
        "PRAGMA user_version=6;");
    transaction.commit();
}
} // namespace atx::server::governance_detail
