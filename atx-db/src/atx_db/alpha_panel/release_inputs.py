"""Independent, exact reader-product snapshots; producer manifests are not trust roots.

No warehouse IO happens on import. Snapshotting is a guarded real-data operation.
Bindings for omitted products must be independently supplied and reviewed, never
generated by copying an incomplete producer manifest.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from . import common as C


def digest(value: Any) -> str:
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"), default=str).encode()).hexdigest()


def identity(path: Path) -> dict[str, Any]:
    before = path.stat()
    sha = C.sha256_file(path)
    after = path.stat()
    if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
        raise RuntimeError(f"input changed while hashing: {path}")
    return {"sha256": sha, "bytes": after.st_size}


def safe_path(root: Path, relative: str) -> Path:
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()) or Path(relative).is_absolute() or ".." in Path(relative).parts:
        raise ValueError(f"unsupported path: {relative}")
    return path


def reader_contract(years=range(2018, 2027)) -> dict[str, dict[str, Any]]:
    """Static inventory from native universe readers, including measurements.

    Optional native branches become mandatory in the release: absence must be
    addressed explicitly rather than silently changing the population/rules.
    Wildcards are reader products, not discovery of arbitrary lake files.
    """
    products = {
        "calendar": ("calendar.parquet", None),
        "finra_names": ("security_master/finra_names.parquet", "security_master/manifest.json"),
        "codes": ("security_master/share_exchange_history.parquet", "security_master/share_exchange_history_manifest.json"),
        "links": ("identity/link_table_v3.parquet", "identity/link_table_v3_manifest.json"),
        "regime": ("sec_filings/filer_regime.parquet", "sec_filings/manifest.json"),
        "filings": ("sec_filings/filings.parquet", "sec_filings/manifest.json"),
        "profile": ("sec_filings/issuer_profile.parquet", "sec_filings/manifest.json"),
        "industry": ("classification/issuer_industry.parquet", "classification/manifest.json"),
        "cover": ("identity_cover/cover_page.parquet", "identity_cover/manifest.json"),
        "headers": ("issuer_history/incorporation.parquet", "issuer_history/manifest.json"),
        "class_headers": ("issuer_classes/incorporation.parquet", "issuer_classes/manifest.json"),
        "reit": ("issuer_classes/reit_status.parquet", "issuer_classes/manifest.json"),
        "reconstitutions": ("indexes/recon_summary.parquet", "indexes/manifest.json"),
    }
    for year in years:
        products[f"panel_{year}"] = (f"panel/year={year}/*.parquet", "panel/manifest.json")
        products[f"shares_{year}"] = (f"market/shares_daily/year={year}/shares_daily.parquet", "market/market_shares_manifest.json")
        products[f"membership_{year}"] = (f"indexes/membership/year={year}/membership.parquet", "indexes/manifest.json")
        if 2020 <= year <= 2025:
            products[f"liquidity_{year}"] = (f"market/liquidity/year={year}/liquidity.parquet", "market/market_liquidity_manifest.json")
            products[f"borrow_{year}"] = (f"borrow_proxy/year={year}/borrow_proxy.parquet", "borrow_proxy/manifest.json")
    return {name: {"pattern": pattern, "manifest": manifest} for name, (pattern, manifest) in products.items()}


def snapshot(root: Path, contract: dict[str, dict[str, Any]], bindings: dict[str, Any],
             code_paths: list[Path], external: dict[str, Path] | None = None) -> dict[str, Any]:
    """Require exact declared product members and verify all producer members.

    Binding shape: {product: {files: {lake-relative: {sha256,bytes}},
    source: nonempty provenance, clock: nonempty rule, admission: nonempty
    independent evidence}}. Bindings also establish allowed wildcard members.
    """
    if set(bindings) != set(contract):
        raise RuntimeError("binding products must equal complete reader contract")
    files, manifests, products = {}, {}, {}
    for name, rule in contract.items():
        binding = bindings[name]
        if not all(isinstance(binding.get(k), str) and binding[k].strip() for k in ("source", "clock", "admission")):
            raise RuntimeError(f"missing independent provenance/clock/admission: {name}")
        declared = binding.get("files", {})
        if not isinstance(declared, dict) or not declared:
            raise RuntimeError(f"empty input product: {name}")
        actual = sorted(p.relative_to(root).as_posix() for p in root.glob(rule["pattern"]) if p.is_file())
        if set(actual) != set(declared):
            raise RuntimeError(f"missing/substituted/unsupported members: {name}")
        for relative in actual:
            measured = identity(safe_path(root, relative))
            if measured != declared[relative]:
                raise RuntimeError(f"stale independently bound input: {relative}")
            files[relative] = measured
        products[name] = binding
        manifest = rule.get("manifest")
        if manifest and manifest not in manifests:
            path = safe_path(root, manifest)
            manifest_identity = identity(path)
            doc = C.read_json(path)
            members = doc.get("files")
            if not isinstance(members, dict) or not members:
                raise RuntimeError(f"empty producer inventory: {manifest}")
            # All declared producer members must actually authenticate; omitted
            # consumed side products are bound above under their explicit name.
            for member, recorded in members.items():
                measured = identity(safe_path(path.parent, member))
                if measured != {"sha256": recorded.get("sha256"), "bytes": recorded.get("bytes")}:
                    raise RuntimeError(f"producer member mismatch: {manifest}/{member}")
            if identity(path) != manifest_identity:
                raise RuntimeError(f"producer manifest changed during snapshot: {manifest}")
            manifests[manifest] = manifest_identity
    return {"version": "reader_snapshot_v1", "contract": contract, "products": products,
            "files": files, "manifests": manifests,
            "external": {name: {"path": str(path.resolve()), **identity(path)} for name, path in (external or {}).items()},
            "code": {str(path.resolve()): identity(path) for path in code_paths}}


def recheck(root: Path, frozen: dict[str, Any]) -> None:
    current = snapshot(root, frozen["contract"], frozen["products"],
                       [Path(path) for path in frozen["code"]],
                       {name: Path(row["path"]) for name, row in frozen["external"].items()})
    if current != frozen:
        raise RuntimeError("source/code snapshot changed; candidate remains unpublished")
