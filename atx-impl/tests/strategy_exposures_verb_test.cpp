// The fitter's factor series, computed from the export exactly as the fitter computes it from
// its own context (Context.book, factor_returns), equals the fitter's own output to 1e-12 for
// a noise signal and a signal loading on beta; the live days, the used rows, the refused
// decision (too-few-usable-names, 42 rows) and the basis rows themselves (numpy's QR sign
// convention) agree; Q is orthonormal on the used rows and 0 elsewhere; the ring and the
// stateless exposures export the same bits.
TEST(Exposures, FitterFactorsEqualTo1e12) {
  const auto f = fitter_fixture();
  const usize end = kD - 2, decisions = end - kBegin;
  const auto ex = export_all(f, kBegin, end);
  ASSERT_EQ(ex.decisions.size(), decisions);
  for (usize j = 0; j < decisions; ++j) {
    const auto& decision = ex.decisions[j];
    const bool refused = kBegin + j == kRefusedSession;
    EXPECT_EQ(decision.refusal, refused ? st::BasisRefusal::TooFewNames : st::BasisRefusal::None)
        << j;
    EXPECT_EQ(refused ? usize{0} : decision.used_rows, kFitterUsedRows[j]) << j;
  }
  EXPECT_EQ(ex.decisions[kRefusedSession - kBegin].used_rows, 42U);
  EXPECT_STREQ(st::basis_refusal_id(st::BasisRefusal::TooFewNames), "too-few-usable-names");
  const auto basis_of = [&](usize j) {
    return std::span<const f64>(ex.basis).subspan(j * kN * kBasis, kN * kBasis);
  };
  const auto forward_of = [&](usize j) {
    return std::span<const f64>(ex.forward).subspan(j * kN, kN);
  };
  for (const auto& [signal, golden] :
       {std::pair{&f.s1, &kFitterS1}, std::pair{&f.s2, &kFitterS2}})
    for (usize j = 0; j < decisions; ++j) {
      const auto row = std::span<const f64>(*signal).subspan((kBegin + j) * kN, kN);
      const auto factor = fitter_factor(basis_of(j), forward_of(j), row);
      const f64 expected = (*golden)[j];
      ASSERT_EQ(factor.live, !std::isnan(expected)) << j;
      if (factor.live) EXPECT_NEAR(factor.value, expected, 1e-12) << j;
    }
  for (const auto& row : kFitterBasis)
    for (usize k = 0; k < kBasis; ++k)
      EXPECT_NEAR(basis_of(row.offset)[row.name * kBasis + k], row.q[k], 1e-12)
          << row.offset << ' ' << row.name << ' ' << k;
  for (usize j = 0; j < decisions; ++j) {
    const auto q = basis_of(j);
    usize used = 0;
    for (usize i = 0; i < kN; ++i) used += q[i * kBasis] != 0 ? 1U : 0U;
    EXPECT_EQ(used, kFitterUsedRows[j]) << j;
    for (usize a = 0; a < kBasis; ++a)
      for (usize b = 0; b < kBasis; ++b) {
        f64 dot = 0;
        for (usize i = 0; i < kN; ++i) dot += q[i * kBasis + a] * q[i * kBasis + b];
        if (used) EXPECT_NEAR(dot, a == b ? 1.0 : 0.0, 1e-12) << j;
      }
  }
  // Interval 150 of name 5 is guarded (adjusted-only doubling): decision 148's label is NaN.
  EXPECT_TRUE(std::isnan(forward_of(148 - kBegin)[5]));
  EXPECT_FALSE(std::isnan(forward_of(147 - kBegin)[5]));
  const auto stateless = export_all(f, kBegin, end, false);
  EXPECT_TRUE(same_bits(stateless.basis, ex.basis));
  EXPECT_TRUE(same_bits(stateless.forward, ex.forward));
}

// neutralization_basis: an orthonormal Q whose projection residual is neutralize_target's OLS
// residual (rescaled to the same gross) to 1e-12; the first column is -1/sqrt(m) (LAPACK's
// sign); refusals in the fitter's order and names; geometry errors.
TEST(Exposures, BasisIsTheOlsProjectionAndRefusesLikeTheFitter) {
  constexpr usize n = 64;
  Lcg rng{9};
  std::vector<f64> exposures(n * st::kPriceExposureCount);
  for (usize i = 0; i < n; ++i) {
    exposures[i * 3 + st::kExposureBeta] = 0.3 + 1.2 * rng.next();
    exposures[i * 3 + st::kExposureVol] = 0.01 + 0.03 * rng.next();
    exposures[i * 3 + st::kExposureLogAdv] = 12.0 + 6.0 * rng.next();
  }
  std::vector<usize> rows;
  for (usize i = 0; i < n; ++i)
    if (i % 9 != 4) rows.push_back(i); // 57 used rows
  const usize m = rows.size();
  const st::PriceExposureConfig cfg{};
  st::NeutralizeScratch scratch;
  std::vector<f64> q(m * kBasis);
  const auto made = st::neutralization_basis(exposures, rows, cfg, scratch, q);
  ASSERT_TRUE(made) << made.error().to_string();
  ASSERT_EQ(*made, st::BasisRefusal::None);
  for (usize r = 0; r < m; ++r)
    EXPECT_NEAR(q[r * kBasis], -1.0 / std::sqrt(static_cast<f64>(m)), 1e-15) << r;
  // A target on the used rows (members = used rows, every row ok): the projection residual,
  // rescaled to the entry gross, is neutralize_target's result.
  std::vector<f64> target(n, 0.0);
  std::vector<u8> member(n, 0), ok(n, 1);
  for (const usize i : rows) {
    member[i] = 1;
    target[i] = exposures[i * 3] + (rng.next() - 0.5);
  }
  f64 mean = 0;
  for (const usize i : rows) mean += target[i] / static_cast<f64>(m);
  for (const usize i : rows) target[i] -= mean;
  auto neutral = target;
  st::NeutralizeStats stats;
  ASSERT_TRUE(st::neutralize_target(neutral, member, exposures, ok, cfg, scratch, stats));
  std::vector<f64> x(m);
  f64 entry = 0;
  for (usize r = 0; r < m; ++r) { x[r] = target[rows[r]]; entry += std::abs(x[r]); }
  for (int pass = 0; pass < 2; ++pass) {
    std::array<f64, kBasis> coef{};
    for (usize k = 0; k < kBasis; ++k)
      for (usize r = 0; r < m; ++r) coef[k] += q[r * kBasis + k] * x[r];
    for (usize r = 0; r < m; ++r)
      for (usize k = 0; k < kBasis; ++k) x[r] -= q[r * kBasis + k] * coef[k];
  }
  f64 gross = 0;
  for (const f64 v : x) gross += std::abs(v);
  for (usize r = 0; r < m; ++r)
    EXPECT_NEAR(x[r] * entry / gross, neutral[rows[r]], 1e-12) << r;
  const auto refusal = [&](std::vector<f64> e, std::vector<usize> used) {
    std::vector<f64> out(used.size() * kBasis);
    const auto r = st::neutralization_basis(e, used, cfg, scratch, out);
    EXPECT_TRUE(r) << (r ? std::string{} : r.error().to_string());
    return r ? *r : st::BasisRefusal::None;
  };
  EXPECT_EQ(refusal(exposures, std::vector<usize>(rows.begin(), rows.begin() + 49)),
            st::BasisRefusal::TooFewNames);
  auto constant = exposures;
  for (usize i = 0; i < n; ++i) constant[i * 3 + st::kExposureVol] = 0.02;
  EXPECT_EQ(refusal(constant, rows), st::BasisRefusal::ConstantExposure);
  auto collinear = exposures;
  for (usize i = 0; i < n; ++i)
    collinear[i * 3 + st::kExposureLogAdv] = 2.0 * collinear[i * 3 + st::kExposureBeta] + 1.0;
  EXPECT_EQ(refusal(collinear, rows), st::BasisRefusal::IllConditioned);
  EXPECT_STREQ(st::basis_refusal_id(st::BasisRefusal::ConstantExposure), "constant-exposure");
  EXPECT_STREQ(st::basis_refusal_id(st::BasisRefusal::IllConditioned),
               "ill-conditioned-exposures");
  EXPECT_STREQ(st::basis_refusal_id(st::BasisRefusal::None), "");
  std::vector<f64> short_basis(m * kBasis - 1);
  auto backwards = rows;
  std::swap(backwards[0], backwards[1]);
  auto bad = exposures;
  bad[rows[3] * 3] = missing;
  for (const auto& status :
       {st::neutralization_basis(exposures, rows, cfg, scratch, short_basis),
        st::neutralization_basis(exposures, backwards, cfg, scratch, q),
        st::neutralization_basis(bad, rows, cfg, scratch, q)}) {
    ASSERT_FALSE(status);
    EXPECT_EQ(status.error().code(), co::ErrorCode::InvalidArgument);
  }
}

