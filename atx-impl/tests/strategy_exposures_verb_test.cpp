struct Lcg {
  u64 state{};
  f64 next() { // [0, 1)
    state = state * 6364136223846793005ULL + 1442695040888963407ULL;
    return static_cast<f64>(state >> 11) * 0x1.0p-53;
  }
};
// test_exposures_export.py fixture(), operation for operation: a one-factor walk with
// per-name loadings, an adjusted-only doubling of name 5 from session 150 (interval 150
// guarded), scattered absent rows, 15 names absent at session 140 (fewer than 50 used names
// at decision 140: refused), scattered nonmembers, and two signals (s1 noise with NaN
// cells, s2 loading on the factor loading).
constexpr usize kD = 170, kN = 60, kBegin = 130, kRefusedSession = 140;
struct Fixture {
  usize dates{}, names{};
  std::vector<f64> close, raw, volume, s1, s2;
  std::vector<u8> present, member;
  [[nodiscard]] st::PriceExposureInput input() const {
    return {dates, names, close, raw, volume, present};
  }
};
Fixture fitter_fixture(usize dates = kD, usize member_from = 0) {
  Fixture f;
  f.dates = dates; f.names = kN;
  const usize cells = dates * kN;
  f.close.assign(cells, 0.0);
  Lcg rng{2026};
  for (usize i = 0; i < kN; ++i) f.close[i] = 20.0 + static_cast<f64>(i);
  for (usize t = 1; t < dates; ++t) {
    const f64 common = 0.03 * (rng.next() - 0.5);
    for (usize i = 0; i < kN; ++i) {
      const f64 loading = 0.5 + 0.02 * static_cast<f64>(i);
      const f64 idio = 0.005 + 0.0002 * static_cast<f64>((i * 7) % kN);
      f.close[t * kN + i] =
          f.close[(t - 1) * kN + i] * (1 + loading * common + idio * (rng.next() - 0.5));
    }
  }
  f.raw = f.close;
  for (usize t = 150; t < dates; ++t) f.close[t * kN + 5] = f.close[t * kN + 5] * 2.0;
  f.volume.assign(cells, 0.0);
  for (usize t = 0; t < dates; ++t)
    for (usize i = 0; i < kN; ++i)
      f.volume[t * kN + i] =
          1e4 * static_cast<f64>(1 + (i * 11) % kN) * (0.5 + rng.next());
  f.present.assign(cells, 1);
  f.member.assign(cells, 0);
  for (usize t = 0; t < dates; ++t)
    for (usize i = 0; i < kN; ++i) {
      const usize k = t * kN + i;
      if ((t * 7 + i * 3) % 97 == 0 || (t == kRefusedSession && i < 15)) f.present[k] = 0;
      f.member[k] = static_cast<u8>(f.present[k] && (t + 2 * i) % 19 != 0 && t >= member_from);
      if (!f.present[k]) f.close[k] = f.raw[k] = f.volume[k] = missing;
    }
  f.s1.assign(cells, 0.0);
  f.s2.assign(cells, 0.0);
  Lcg draws{77};
  for (usize t = 0; t < dates; ++t)
    for (usize i = 0; i < kN; ++i) {
      const usize k = t * kN + i;
      f.s1[k] = draws.next() - 0.5;
      f.s2[k] = (0.5 + 0.02 * static_cast<f64>(i)) + 0.2 * (draws.next() - 0.5);
      if ((t * 3 + i) % 23 == 0) f.s1[k] = missing;
    }
  return f;
}
// The export of decisions [begin, end) in memory.
struct Export {
  std::vector<f64> basis, forward;
  std::vector<st::ExposureDecision> decisions;
};
Export export_all(const Fixture& f, usize begin, usize end, bool ring = true) {
  Export out;
  const auto panel = f.input();
  st::ExposureExportScratch scratch;
  if (ring) st::enable_session_ring(scratch.exposure, panel);
  std::vector<f64> basis(kN * kBasis), forward(kN);
  for (usize d = begin; d < end; ++d) {
    const auto decision = st::export_decision(panel, f.member, st::PriceExposureConfig{}, d,
                                              scratch, basis, forward);
    EXPECT_TRUE(decision) << d << ' ' << (decision ? std::string{} : decision.error().to_string());
    if (!decision) return out;
    out.decisions.push_back(*decision);
    out.basis.insert(out.basis.end(), basis.begin(), basis.end());
    out.forward.insert(out.forward.end(), forward.begin(), forward.end());
  }
  return out;
}
// fit_composition_weights.py centered_tied_ranks for one row: over the valid cells, a tie
// group [b, e) of the ascending order gets (b + (e - 1)) / (2 (n - 1)) - 0.5; 0 elsewhere
// and on rows with fewer than two valid cells.
std::vector<f64> centered_ranks(std::span<const f64> x, const std::vector<u8>& valid) {
  std::vector<usize> order;
  for (usize i = 0; i < x.size(); ++i)
    if (valid[i]) order.push_back(i);
  std::vector<f64> out(x.size(), 0.0);
  const usize n = order.size();
  if (n < 2) return out;
  std::sort(order.begin(), order.end(), [&](usize a, usize b) { return x[a] < x[b]; });
  for (usize b = 0; b < n;) {
    usize e = b + 1;
    while (e < n && x[order[e]] == x[order[b]]) ++e;
    const f64 rank = (static_cast<f64>(b) + static_cast<f64>(e - 1)) /
                     (2.0 * static_cast<f64>(n - 1)) - 0.5;
    for (usize k = b; k < e; ++k) out[order[k]] = rank;
    b = e;
  }
  return out;
}
// The fitter's Context.book + factor_returns on one exported decision: ranks over the used
// names with a finite signal, projected out of the basis twice (one refinement, as the fitter),
// gross 1 when live (entry > 0, finite gross > 1e-9 entry), f = sum q fwd (NaN fwd as 0).
struct Factor {
  bool live{};
  f64 value{};
};
Factor fitter_factor(std::span<const f64> basis, std::span<const f64> forward,
                     std::span<const f64> signal) {
  const usize n = signal.size();
  std::vector<u8> valid(n);
  for (usize i = 0; i < n; ++i)
    valid[i] = static_cast<u8>(basis[i * kBasis] != 0 && std::isfinite(signal[i]));
  auto x = centered_ranks(signal, valid);
  f64 entry = 0;
  for (const f64 v : x) entry += std::abs(v);
  for (int pass = 0; pass < 2; ++pass) {
    std::array<f64, kBasis> coef{};
    for (usize k = 0; k < kBasis; ++k)
      for (usize i = 0; i < n; ++i) coef[k] += basis[i * kBasis + k] * x[i];
    for (usize i = 0; i < n; ++i)
      for (usize k = 0; k < kBasis; ++k) x[i] -= basis[i * kBasis + k] * coef[k];
  }
  f64 gross = 0;
  for (const f64 v : x) gross += std::abs(v);
  Factor out;
  out.live = entry > 0 && std::isfinite(gross) && gross > 1e-9 * entry;
  if (!out.live) return out;
  for (usize i = 0; i < n; ++i)
    out.value += x[i] / gross * (std::isnan(forward[i]) ? 0.0 : forward[i]);
  return out;
}
bool same_bits(std::span<const f64> a, std::span<const f64> b) {
  if (a.size() != b.size()) return false;
  for (usize k = 0; k < a.size(); ++k)
    if (std::bit_cast<u64>(a[k]) != std::bit_cast<u64>(b[k])) return false;
  return true;
}

