// The verb on a pinned engine role: basis.f64 (decisions x names x 4) and forward_returns.f64
// (decisions x names) hold export_decision's bits for [score_begin, score_end - 2), and
// manifest.json (last) their SHAs, the window, the used rows and the refusals.
TEST(Exposures, VerbWritesTheK2Layout) {
  const auto f = fitter_fixture(kRoleDates, 63);
  Directory dir;
  const auto role = write_role(dir.path / "role", f);
  const auto out = dir.path / "export";
  std::ostringstream o, e;
  ASSERT_EQ(dispatch({"exposures", "--role", role.path, "--role-sha256", role.sha, "--output",
                      out.string()}, o, e), 0) << e.str();
  const usize end = kRoleDates - 2, decisions = end - kScoreBegin;
  const auto basis = read_all<f64>(out / "basis.f64");
  const auto forward = read_all<f64>(out / "forward_returns.f64");
  ASSERT_EQ(basis.size(), decisions * kN * kBasis);
  ASSERT_EQ(forward.size(), decisions * kN);
  const auto expected = export_all(f, kScoreBegin, end);
  EXPECT_TRUE(same_bits(basis, expected.basis));
  EXPECT_TRUE(same_bits(forward, expected.forward));
  const auto manifest = read_json(out / "manifest.json");
  EXPECT_EQ(manifest.at("schema"), "atx.price-risk-exposures/v1");
  EXPECT_EQ(manifest.at("status"), "complete");
  EXPECT_EQ(manifest.at("role_manifest_sha256"), role.sha);
  EXPECT_EQ(manifest.at("research_window"), "research-window-v2");
  EXPECT_EQ(manifest.at("decision_begin"), kScoreBegin);
  EXPECT_EQ(manifest.at("decision_end_exclusive"), end);
  EXPECT_EQ(manifest.at("decisions"), decisions);
  EXPECT_EQ(manifest.at("instruments"), kN);
  EXPECT_EQ(manifest.at("ids_sha256"), role.manifest.at("files").at("ids.u64").at("sha256"));
  const auto& files = manifest.at("files");
  EXPECT_EQ(files.at("basis.f64").at("sha256"),
            co::sha256_file((out / "basis.f64").string()).value());
  EXPECT_EQ(files.at("forward_returns.f64").at("sha256"),
            co::sha256_file((out / "forward_returns.f64").string()).value());
  EXPECT_EQ(files.at("basis.f64").at("shape"), Json::array({decisions, kN, kBasis}));
  EXPECT_EQ(files.at("basis.f64").at("bytes"), decisions * kN * kBasis * sizeof(f64));
  ASSERT_EQ(manifest.at("used_rows").size(), decisions);
  usize refused = 0;
  for (usize j = 0; j < decisions; ++j) {
    const auto& decision = expected.decisions[j];
    const bool has_basis = decision.refusal == st::BasisRefusal::None;
    EXPECT_EQ(manifest.at("used_rows")[j], has_basis ? decision.used_rows : usize{0}) << j;
    refused += has_basis ? 0U : 1U;
  }
  EXPECT_EQ(manifest.at("refused").size(), refused);
  EXPECT_NE(o.str().find("exposures: 35 decisions"), std::string::npos) << o.str();
}

// Refusals before any output: a wrong pin, an existing output, a role whose score window
// reaches the research-window seal (no payload is opened), usage errors.
TEST(Exposures, VerbRefusesBeforeAnyOutput) {
  const auto f = fitter_fixture(kRoleDates, 63);
  Directory dir;
  const auto role = write_role(dir.path / "role", f);
  const auto out = dir.path / "never";
  std::ostringstream o, e;
  const auto run = [&](const std::string& path, const std::string& sha) {
    return dispatch({"exposures", "--role", path, "--role-sha256", sha, "--output", out.string()},
                    o, e);
  };
  EXPECT_EQ(run(role.path, std::string(64, 'b')), 1);
  EXPECT_FALSE(std::filesystem::exists(out));
  auto sealed = role.manifest;
  sealed["score_end_ns"] = 1'704'153'600'000'000'000LL; // 2024-01-02
  const auto sealed_path = (dir.path / "role" / "sealed.json").string();
  const auto sealed_sha = write_json(sealed_path, sealed);
  e.str("");
  EXPECT_EQ(run(sealed_path, sealed_sha), 1);
  EXPECT_NE(e.str().find("research-window-v2"), std::string::npos) << e.str();
  EXPECT_FALSE(std::filesystem::exists(out));
  ASSERT_TRUE(std::filesystem::create_directory(out));
  EXPECT_EQ(run(role.path, role.sha), 1);
  EXPECT_TRUE(std::filesystem::is_empty(out));
  EXPECT_EQ(dispatch({"exposures", "--role", role.path, "--output", (dir.path / "x").string()},
                     o, e), 2);
  EXPECT_EQ(dispatch({"exposures", "--role", role.path, "--bogus", "1"}, o, e), 2);
  EXPECT_EQ(dispatch({"exposures", "--max-bytes", "x"}, o, e), 2);
  EXPECT_FALSE(std::filesystem::exists(dir.path / "x"));
}
